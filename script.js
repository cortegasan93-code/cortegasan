function cardWrap(item, cls, lang) {
  const type = item.type[lang] || item.type.es;
  const text = item.text[lang] || item.text.es;
  const footerArrow = item.link ? '↗' : '•';
  const inner = `
    <div class="card-meta"><span>${type}</span><span>${item.year}</span></div>
    <h3>${item.title}</h3>
    <p>${text}</p>
    <div class="card-footer"><span>${item.venue}</span><span>${footerArrow}</span></div>
  `;
  if (item.link) {
    return `<a class="${cls}" href="${item.link}" target="_blank" rel="noreferrer">${inner}</a>`;
  }
  return `<article class="${cls}">${inner}</article>`;
}

function renderAcademia(lang) {
  document.getElementById('academia-rail').innerHTML = academiaItems.map(item => cardWrap(item, 'rail-card', lang)).join('');
}
function renderAnalysis(lang) {
  document.getElementById('analysis-rail').innerHTML = analysisItems.map(item => cardWrap(item, 'analysis-card', lang)).join('');
}
function renderStack(items, targetId, lang) {
  const html = items.map(item => `
    <article class="stack-item">
      <time>${item.date}</time>
      <div>
        <h4>${item.title[lang] || item.title.es}</h4>
        <p>${item.text[lang] || item.text.es}</p>
        <span class="meta-note">${item.note[lang] || item.note.es}</span>
      </div>
    </article>
  `).join('');
  document.getElementById(targetId).innerHTML = html;
}

function setLanguage(lang) {
  const dict = translations[lang] || translations.es;
  document.documentElement.lang = lang;
  document.querySelectorAll('[data-i18n]').forEach(el => {
    const key = el.dataset.i18n;
    if (dict[key]) el.textContent = dict[key];
  });
  document.querySelectorAll('.lang-btn').forEach(btn => {
    const active = btn.dataset.lang === lang;
    btn.classList.toggle('active', active);
    btn.setAttribute('aria-pressed', String(active));
  });
  renderAcademia(lang);
  renderAnalysis(lang);
  renderStack(talksItems, 'talks-list', lang);
  renderStack(programsItems, 'programs-list', lang);
  localStorage.setItem('cos-lang', lang);
}

document.querySelectorAll('.lang-btn').forEach(btn => {
  btn.addEventListener('click', () => setLanguage(btn.dataset.lang));
});

document.querySelectorAll('.rail-btn').forEach(btn => {
  btn.addEventListener('click', () => {
    const target = document.getElementById(btn.dataset.target);
    const direction = btn.dataset.direction === 'right' ? 1 : -1;
    target.scrollBy({ left: direction * 360, behavior: 'smooth' });
  });
});

